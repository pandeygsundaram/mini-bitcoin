// Dependency-free rendezvous service. Carries presence and WebRTC signaling only.
import http from 'node:http';
import { randomUUID, randomBytes, createHmac } from 'node:crypto';
import { pathToFileURL } from 'node:url';
export const NETWORK = 'mini-bitcoin-browser-v2';
export function createSignalingServer(options = {}) {
  const peers = new Map();
  const origins = options.origins || (process.env.ALLOWED_ORIGINS || 'http://localhost:8080,http://127.0.0.1:8080').split(',');
  const ttl = options.ttl || 35000;
  const maxPeers = Number(process.env.MAX_PEERS || 500);
  const event = (peer, type, data) => {
    if (!peer.stream || peer.stream.destroyed) {
      if (type === 'signal') { peer.queued ||= []; if(peer.queued.length < 128) peer.queued.push({ type, data }); }
      return;
    }
    if (peer.stream.writableLength > 262144) { peer.stream.destroy(); return; }
    peer.stream.write(`event: ${type}\ndata: ${JSON.stringify(data)}\n\n`);
  };
  const list = () => [...peers.values()].map(p => ({ id: p.id, ...p.presence }));
  const publish = () => { const data = list(); for (const peer of peers.values()) event(peer, 'peers', data); };
  const prune = setInterval(() => {
    let changed = false;
    for (const [id, peer] of peers) if (Date.now() - peer.lastSeen > ttl) { peer.stream?.end(); peers.delete(id); changed = true; }
    if (changed) publish();
    for (const peer of peers.values()) event(peer, 'heartbeat', { now: Date.now() });
  }, Math.min(10000, ttl));
  prune.unref();
  const safePresence = p => ({ node: p?.node === true, mining: p?.mining === true, height: Number.isSafeInteger(p?.height) && p.height >= 0 ? p.height : 0 });
  const read = async request => {
    let size = 0, parts = [];
    for await (const chunk of request) { size += chunk.length; if (size > 32768) throw Object.assign(new Error('Payload too large'), { status: 413 }); parts.push(chunk); }
    return JSON.parse(Buffer.concat(parts).toString() || '{}');
  };
  const counts = new Map();
  const server = http.createServer(async (req, res) => {
    const origin = req.headers.origin;
    if (origin && !origins.includes(origin)) { res.writeHead(403).end(); return; }
    if (origin) res.setHeader('Access-Control-Allow-Origin', origin);
    res.setHeader('Vary', 'Origin');
    res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');
    res.setHeader('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
    res.setHeader('Cache-Control', 'no-store');
    if (req.method === 'OPTIONS') { res.writeHead(204).end(); return; }
    const reply = (status, data) => { res.writeHead(status, { 'Content-Type': 'application/json' }); res.end(JSON.stringify(data)); };
    try {
      const url = new URL(req.url, 'http://localhost');
      if (url.pathname === '/health' && req.method === 'GET') { reply(200, { ok: true, network: NETWORK, peers: peers.size }); return; }
      const ip = req.socket.remoteAddress;
      const token = req.headers.authorization?.replace(/^Bearer /, '');
      const authenticatedPeer = [...peers.values()].find(p => p.token === token);
      const rateKey = url.pathname === '/v1/register' ? ip : authenticatedPeer?.id || ip;
      const bucket = Math.floor(Date.now()/60000);
      const rate = counts.get(rateKey);
      const next = rate?.bucket === bucket ? { bucket, count: rate.count + 1 } : { bucket, count: 1 };
      counts.set(rateKey, next);
      if (counts.size > 2000) for (const [ip, r] of counts) if (r.bucket !== bucket) counts.delete(ip);
      if (next.count > 300) { reply(429, { error: 'Too many requests' }); return; }
      if (url.pathname === '/v1/register' && req.method === 'POST') {
        const data = await read(req);
        if (data.network !== NETWORK) { reply(400, { error: 'Wrong network' }); return; }
        if (peers.size >= maxPeers) { reply(503, { error: 'Discovery service full' }); return; }
        // IDs and tokens are generated by the service, preventing peer takeover.
        const id = randomUUID(), token = randomBytes(32).toString('hex');
        const peer = { id, token, lastSeen: Date.now(), presence: safePresence(data.presence) };
        peers.set(id, peer);
        const iceServers = [];
        const stun = (process.env.STUN_URLS || '').split(',').filter(Boolean);
        if (stun.length) iceServers.push({ urls: stun });
        if (process.env.TURN_URLS && process.env.TURN_SECRET) {
          const username = `${Math.floor(Date.now()/1000)+3600}:${id}`;
          iceServers.push({ urls: process.env.TURN_URLS.split(','), username, credential: createHmac('sha1', process.env.TURN_SECRET).update(username).digest('base64') });
        }
        reply(200, { id, token, peers: list(), iceServers }); publish(); return;
      }
      const peer = authenticatedPeer;
      if (!peer) { reply(401, { error: 'Unknown or expired session' }); return; }
      peer.lastSeen = Date.now();
      if (url.pathname === '/v1/events' && req.method === 'GET') {
        peer.stream?.end();
        res.writeHead(200, { 'Content-Type': 'text/event-stream', 'Connection': 'keep-alive', 'X-Accel-Buffering': 'no' });
        peer.stream = res; event(peer, 'peers', list());
        for(const item of peer.queued || []) event(peer, item.type, item.data); peer.queued = [];
        res.on('close', () => { if (peer.stream === res) peer.stream = null; }); return;
      }
      if (url.pathname === '/v1/presence' && req.method === 'POST') { peer.presence = safePresence(await read(req)); reply(200, { ok: true }); publish(); return; }
      if (url.pathname === '/v1/signal' && req.method === 'POST') {
        const data = await read(req);
        const target = peers.get(data.to);
        const signal = data.signal;
        if (!target || target.id === peer.id) { reply(404, { error: 'Peer unavailable' }); return; }
        if (!signal || !['offer', 'answer', 'candidate'].includes(signal.type)) { reply(400, { error: 'Invalid signal' }); return; }
        event(target, 'signal', { from: peer.id, signal }); reply(200, { ok: true }); return;
      }
      if (url.pathname === '/v1/leave' && req.method === 'POST') { peer.stream?.end(); peers.delete(peer.id); reply(200, { ok: true }); publish(); return; }
      reply(404, { error: 'Not found' });
    } catch (error) { if (!res.headersSent) reply(error.status || 400, { error: error.status ? error.message : 'Invalid request' }); else res.end(); }
  });
  server.on('close', () => clearInterval(prune));
  return server;
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const port = Number(process.env.PORT || 8787);
  createSignalingServer().listen(port, '0.0.0.0', () => console.log(`Mini-Bitcoin signaling listening on :${port}`));
}
